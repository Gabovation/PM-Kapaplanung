run("currentPeriod=()=>date('2026-11-09')");
assert.match(run('overview()'),/Gewonnene Projektstunden<\/div><div class="value">12 <small>h<\/small><\/div><div class="caption">Gesamtbudget · 09\.11\.26 – 15\.11\.26: 12 h/);
assert.match(run('overview()'),/Erwartete Projektstunden<\/div><div class="value">8 <small>h<\/small><\/div><div class="caption">Gesamtbudget · 09\.11\.26 – 15\.11\.26: 8 h/);
assert.doesNotMatch(run('overview()'),/Produktivität und Personalbedarf/);
assert.match(run('overview()'),/Kapazität und Engpässe/);
assert.equal(run('pl.capacity'),60);
assert.equal(run('pl.target'),42);
assert.equal(run('pl.planned'),10);
assert.ok(Math.abs(run('pl.productivity')-10/60*100)<1e-9);
assert.equal(run('pl.difference'),32);
assert.equal(run('pl.fteDifference'),1);
assert.equal(run('anna.target'),32);
assert.equal(run('anna.fteDifference'),22/32);
assert.equal(run('bernd.target'),10);
assert.equal(run('bernd.fteDifference'),0.5);
assert.equal(run('qvp.target'),0);
assert.equal(run('qvp.difference'),-5);
assert.equal(run('qvp.fteDifference'),null);
run(`const fourHours=KapaCapacity.build({...state,projects:[{...base,id:'four',status:'Gewonnen'}]},'2026-11-09','week',1);
const fourProductivity=KapaCapacity.productivity(fourHours,['a'],80,40)[0];`);
